# recentrer horizontalement dans 21 colonnes, 21 lignes
def lantern():
    rows = [r[4:13] for r in LANTERNE]
    pad_l = (21 - 9) // 2
    rows = ["." * pad_l + r + "." * (21 - 9 - pad_l) for r in rows]
    top = (21 - len(rows)) // 2
    return ["." * 21] * top + rows + ["." * 21] * (21 - len(rows) - top)
